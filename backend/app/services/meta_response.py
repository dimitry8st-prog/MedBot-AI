"""
Обработка мета-вопросов о боте (приоритет №1, выше медицинского поиска).

Определение по смыслу, не только по точному совпадению фраз.
Не вызывает RAG / веб-поиск.
"""

from __future__ import annotations

import re

META_REPLY = """👋 Привет! Я MedBot-AI — ваш справочный ассистент для врачей и студентов-медиков.

✅ *Что я умею:*
1. Отвечать на вопросы по терапии, диагностике и лечению заболеваний.
2. Искать информацию во внутренней базе знаний и актуальных клинических рекомендациях.
3. Если в базе данных недостаточно — искать в авторитетных медицинских источниках интернета (RU+EN).
4. Давать ответ в фиксированной структуре с указанием источника и года протокола.

⚠️ *Важно:* Я только справочный инструмент. Мои ответы не заменяют консультацию врача и профессиональное медицинское образование.

💡 *Примеры хороших вопросов:*
- «Первая линия терапии гипертонии»
- «Симптомы аппендицита»
- «Лечение мигрени по клиническим рекомендациям»"""

_META_EXACT = {
    "помощь",
    "хелп",
    "help",
    "старт",
    "start",
    "привет",
    "здравствуй",
    "здравствуйте",
    "хай",
    "hello",
    "hi",
    "йоу",
    "меню",
    "инфо",
    "информация",
    "о боте",
}

_META_PATTERNS = (
    r"что\s+ты\s+умеешь",
    r"чем\s+ты\s+занимаешься",
    r"кто\s+ты(?:\s+такой)?",
    r"как\s+тобой\s+пользоваться",
    r"как\s+(?:мне\s+)?пользоваться",
    r"как\s+с\s+тобой\s+работать",
    r"что\s+ты\s+можешь",
    r"какие\s+у\s+тебя\s+функци",
    r"расскажи\s+о\s+себе",
    r"чем\s+ты\s+можешь\s+помочь",
    r"твои\s+возможност",
    r"как\s+ты\s+работаешь",
    r"что\s+умеешь",
    r"для\s+чего\s+ты",
    r"зачем\s+ты\s+нужен",
    r"тво[яё]\s+роль",
    r"представься",
    r"help\s*me",
    r"who\s+are\s+you",
    r"what\s+can\s+you\s+do",
    r"how\s+to\s+use\s+(you|the\s+bot)",
)


def is_meta_question(text: str) -> bool:
    """True, если вопрос о боте / приветствие / помощь — без медпоиска."""
    raw = (text or "").strip()
    if not raw:
        return False

    if raw.startswith("/"):
        cmd = raw.split()[0].casefold().lstrip("/")
        if cmd in {"start", "help", "помощь", "about", "info", "menu"}:
            return True

    cleaned = re.sub(r"[^\w\sа-яА-ЯёЁ?/]", " ", raw, flags=re.UNICODE)
    cleaned = re.sub(r"\s+", " ", cleaned).strip().casefold()

    if cleaned in _META_EXACT:
        return True

    # короткие приветствия / «добрый день» и т.п.
    if len(cleaned.split()) <= 4 and any(
        cleaned.startswith(g)
        for g in ("привет", "здравств", "добрый", "доброе", "доброго", "hi", "hello", "hey")
    ):
        return True

    return any(re.search(p, cleaned) for p in _META_PATTERNS)


def meta_answer() -> str:
    return META_REPLY
